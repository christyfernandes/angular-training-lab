// Generates the learner-facing Markdown docs from public/content/learning-path.json.
//
//   npm run docs:learning
//
// One source of truth: the in-app /learn page and these docs both come from the same JSON,
// so the order, links and exercises can never drift apart. Edit the JSON, then re-run this.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const path = JSON.parse(readFileSync(join(root, 'public/content/learning-path.json'), 'utf8'));
const NOTICE = '<!-- Generated by `npm run docs:learning` from public/content/learning-path.json. Do not edit by hand. -->\n\n';
const KIND = { setup: 'Set up', read: 'Read', watch: 'Watch', explore: 'Explore in the app', study: 'Study the code', exercise: 'Exercise', check: 'Self-check' };
const trackLabel = (t) => (t === 'both' ? 'Both tracks' : t === 'foundations' ? 'Foundations only' : 'Accelerated only');
const conceptName = (id) => path.concepts.find((c) => c.id === id)?.name ?? id;
const rel = (file) => `../../${file}`;
const write = (file, text) => {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), NOTICE + text.trim() + '\n');
  console.log('wrote', file);
};

// 1. One file per stage, steps in order, as a checklist learners can tick in their fork.
for (const [index, stage] of path.stages.entries()) {
  const prev = path.stages[index - 1];
  const next = path.stages[index + 1];
  const lines = [`# ${stage.label}: ${stage.title}`, '', `**Goal:** ${stage.goal}`, '', `About ${stage.hours} hours. Do the steps in order; skip steps marked for the other track.`, ''];
  stage.steps.forEach((step, i) => {
    const title = step.url ? `[${step.title}](${step.url})` : step.title;
    lines.push(`## ${i + 1}. ${KIND[step.kind]}: ${title}`, '');
    lines.push(`- [ ] Done · ${trackLabel(step.track)} · about ${step.minutes} min`);
    if (step.route) lines.push(`- Open in the running app: \`http://localhost:4200${step.route}\``);
    if (step.files?.length) lines.push(`- Files: ${step.files.map((f) => `[\`${f}\`](${rel(f)})`).join(', ')}`);
    if (step.lookFor) lines.push(`- Look for: ${step.lookFor}`);
    if (step.note) lines.push(`- ${step.note}`);
    if (step.doneWhen) lines.push(`- Done when: ${step.doneWhen}`);
    if (step.questions?.length) step.questions.forEach((q, n) => lines.push(`  ${n + 1}. ${q}`));
    if (step.concepts.length) lines.push(`- Concepts: ${step.concepts.map(conceptName).join(', ')}`);
    lines.push('');
  });
  if (stage.checkpoint) lines.push(`## ${stage.checkpoint.title}`, '', stage.checkpoint.submit, '');
  lines.push('---', '', [prev && `← [${prev.label}: ${prev.title}](${prev.id}.md)`, '[All stages](README.md)', next && `[${next.label}: ${next.title}](${next.id}.md) →`].filter(Boolean).join(' · '));
  write(`docs/learning-path/${stage.id}.md`, lines.join('\n'));
}

// 2. The index: the order learners move in.
write('docs/learning-path/README.md', [
  `# ${path.title}`, '', path.intro, '',
  ...path.tracks.map((t) => `- **${t.name}:** ${t.description}`), '',
  '| Order | Stage | Hours | Steps | Ends with |', '| --- | --- | --- | --- | --- |',
  ...path.stages.map((s, i) => `| ${i + 1} | [${s.label}: ${s.title}](${s.id}.md) | ${s.hours} | ${s.steps.length} | ${s.checkpoint ? s.checkpoint.title : '–'} |`),
  '', 'Prefer clicking? Run the app and open **Learn** (`/learn`): same steps, with progress tracking.',
].join('\n'));

// 3. Concept map: every concept → where to read, watch, see it, and practise.
const byConcept = path.concepts.map((c) => {
  const hits = path.stages.flatMap((stage) => stage.steps.filter((s) => s.concepts.includes(c.id)).map((s) => ({ stage, s })));
  const link = (k) => [...new Map(hits.filter((h) => h.s.kind === k && h.s.url).map((h) => [h.s.url, `[${h.s.title.split(':')[0]}](${h.s.url})`])).values()];
  const routes = [...new Set(hits.filter((h) => h.s.route).map((h) => `\`${h.s.route}\``))];
  const files = [...new Set(hits.flatMap((h) => (h.s.kind === 'explore' || h.s.kind === 'study' ? h.s.files ?? [] : [])))].slice(0, 3);
  const exercises = hits.filter((h) => h.s.kind === 'exercise').map((h) => `${h.stage.label} (${trackLabel(h.s.track).replace(' only', '')})`);
  const weeks = [...new Set(hits.map((h) => h.stage.label))];
  return `| ${c.name} | ${weeks.join(', ')} | ${link('read').join('<br>') || '–'} | ${link('watch').join('<br>') || '–'} | ${routes.join(' ') || '–'} | ${files.map((f) => `[\`${f.split('/').pop()}\`](../${f})`).join('<br>') || '–'} | ${[...new Set(exercises)].join('<br>') || '–'} |`;
});
write('docs/CONCEPT-MAP.md', [
  '# Concept map', '', 'Each concept, the stage that teaches it, what to read and watch, where to see it in the running app, which code to study and where you practise it.', '',
  '| Concept | Stage | Read | Watch | See it in the app | Code | Practise |', '| --- | --- | --- | --- | --- | --- | --- |', ...byConcept,
].join('\n'));

// 4. Curated resources.
write('docs/RESOURCES.md', [
  '# Curated resources', '', 'Free official material first. Paid courses only where your organization already has a licence.', '',
  '| Resource | Type | Cost | Best for |', '| --- | --- | --- | --- |',
  ...path.resources.map((r) => `| [${r.title}](${r.url}) | ${r.type} | ${r.cost} | ${r.bestFor} |`),
  '', 'Prefer videos from 2024 or later; older ones teach NgModules, `*ngIf` and decorator inputs.',
].join('\n'));

// 5. Exercises, grouped by stage.
write('EXERCISES.md', [
  '# Exercises', '', 'One pull request per exercise, using the PR template. Ask your review buddy to review within 24 hours.', '',
  ...path.stages.flatMap((stage) => {
    const ex = stage.steps.filter((s) => s.kind === 'exercise');
    if (!ex.length) return [];
    return [`## ${stage.label}: ${stage.title}`, '', ...ex.map((s) => `- **${trackLabel(s.track).replace(' only', '')}:** ${s.title}. Files: ${s.files.map((f) => `\`${f}\``).join(', ')}${s.doneWhen ? `. ${s.doneWhen}` : ''}`), ''];
  }),
  '## Definition of done (every exercise)', '',
  '- `npm run build` has no warnings and `npm run test:all` passes.',
  '- New user-facing strings are in every translation file.',
  '- Components use semantic theme tokens only.',
  '- The PR description includes your progress summary (Learn page → "Copy progress for your PR").',
].join('\n'));
